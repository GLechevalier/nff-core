void app_main(void) {
    console_init();   // route esp_log into the 0xC0FF-over-PPP console (UART0 is the PPP link)
    // nff_log() bypasses esp_log and printf()s raw to UART0 (stdout) — that would corrupt PPP, so
    // silence it; the diagnostic-critical logs (esp-mqtt/esp-tls) flow through the esp_log hook.
    nff_log_set_quiet(true);
    nvs_flash_init();
    wifi_connect();

    if (nff_init(&g_cfg) != NFF_OK) {
        ESP_LOGE(TAG, "nff_init failed");
        return;
    }

    // The universal image builds with NFF_BOOTSTRAP_ENABLED=0, so nff_init never overlays the
    // operational creds this device persisted at claim rollover (op_cert/op_key/op_chain in NVS) —
    // on real silicon it would dial the broker with NO client cert and the stub device_id, and the
    // broker drops the MQTT CONNECT (transport_read EOF, seen live on 1.0.15). Overlay the claim
    // store here instead. QEMU is untouched: its NVS identity loader already filled client_cert,
    // and the guard skips a cfg that carries creds. device_id must become the hardware id — it is
    // the operational cert's CN and the broker's ACL requires client_id == CN.
    if (!g_cfg.client_cert || g_cfg.client_cert_len == 0) {
        static nff_config_t s_claimed;         // blobs stay malloc'd for the life of the device
        static char         s_hwid[24];
        if (nff_store_is_claimed() && nff_store_load(&g_cfg, &s_claimed) == NFF_OK) {
            nff_port_get_unique_id(s_hwid, sizeof(s_hwid));
            s_claimed.device_id = s_hwid;
            g_cfg = s_claimed;                 // nff keeps a pointer to g_cfg; update it in place
            ESP_LOGI(TAG, "claim store creds loaded (id=%s, chain=%u B)",
                     s_hwid, (unsigned)g_cfg.client_cert_len);
        } else {
            ESP_LOGW(TAG, "no claim store creds — MQTT will connect without a client cert");
        }
    }

    // The claim store predates op_ca provisioning on this fleet (op_ca is empty), so ca_cert is
    // still NULL after the overlay. Without a CA, esp-tls aborts setup ("No server verification
    // option set", 0x8017). Supply the baked fleet root CA as a fallback so the broker can be
    // verified. The port reads cfg->ca_cert lazily at connect, so setting it here (before
    // nff_connect) takes effect.
    if (!g_cfg.ca_cert || g_cfg.ca_cert_len == 0) {
        g_cfg.ca_cert     = FLEET_ROOT_CA_DER;
        g_cfg.ca_cert_len = sizeof(FLEET_ROOT_CA_DER);
        ESP_LOGW(TAG, "claim store had no CA — using baked fleet root CA (%u B)",
                 (unsigned)sizeof(FLEET_ROOT_CA_DER));
    }

    // Cut-the-cord broker override: on WiFi, the wired path's synthetic broker hostname (only
    // ever resolved by the browser link's local DNS) is unreachable — dial where the handoff
    // said the fleet really lives. Applied AFTER the claim-store overlay (which rebuilds g_cfg)
    // and only on a WiFi boot; absent key = wired boot or no handoff yet, nothing changes.
    // The port:port split and number parse are index math on purpose (no `Type *v = call()`,
    // no division by an identifier — nff-ota's analyzer reads both as the demo's faults).
    {
        static char s_broker[80];
        if (s_wifi_up &&
            nff_port_nvs_get_str("wifi_broker", s_broker, sizeof(s_broker)) == 0 &&
            s_broker[0] != '\0') {
            size_t cut = 0;
            for (size_t i = 0; s_broker[i] != '\0'; i++) {
                if (s_broker[i] == ':') cut = i;
            }
            int port = 0;
            if (cut > 0) {
                for (size_t i = cut + 1; s_broker[i] >= '0' && s_broker[i] <= '9'; i++) {
                    port = port * 10 + (s_broker[i] - '0');
                }
                s_broker[cut] = '\0';
            }
            g_cfg.broker_host = s_broker;
            if (port > 0 && port <= 65535) g_cfg.broker_port = (uint16_t)port;
            ESP_LOGI(TAG, "wifi broker override: %s:%d", s_broker, (int)g_cfg.broker_port);
        }
    }

    // Gate the OTA commit/rollback on our own notion of healthy before connecting.
    nff_register_health_check(on_health_check, NULL);

    // nff_connect() publishes any coredump left by a prior panic, so a crash-loop reports every boot.
    nff_connect();
    // rst tells post-OTA reboots apart: 12 = SW_CPU (deliberate esp_restart, e.g. a completed
    // flip) vs 1 = POWERON (external EN pulse — e.g. the serial link resetting the chip).
    ESP_LOGI(TAG, "=== wired console up (0xC0FF over PPP), fw=%s rst=%d — nff services starting ===",
             NFF_FW_VERSION, (int)esp_reset_reason());

    // nff services MQTT/heartbeat/commands/OTA on its own task (Core 0); the app runs on Core 1.
    nff_start_task();
    xTaskCreate(app_task, "app", 4096, NULL, 5, NULL);
}
