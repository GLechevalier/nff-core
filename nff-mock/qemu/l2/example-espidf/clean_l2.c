#include "nff_store.h"     // claim-store overlay for the universal (credential-less) image
#include "nff_port.h"      // nff_port_get_unique_id — device_id == operational cert CN
#include "credentials.h"   // generated by: nff provision new-device --id <device-id>

#include "esp_log.h"
#include "esp_wifi.h"
#include "esp_event.h"
