import datetime
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.x509 import load_pem_x509_certificate

from nff_fleet import signing
from nff_fleet.config import settings
from nff_fleet.provisioning.ca import project_ca_cert_der, project_id_from_cert


def _to_c_array(name: str, data: bytes) -> str:
    hex_bytes = ", ".join(f"0x{b:02x}" for b in data)
    len_name = name.replace("_DER", "_LEN") if "_DER" in name else f"{name}_LEN"
    return (
        f"static const uint8_t {name}[] = {{\n    {hex_bytes}\n}};\n"
        f"#define {len_name} sizeof({name})\n"
    )


def render_credentials_h(device_id: str) -> str:
    device_dir = settings.certs_dir / device_id

    # Device client cert (mTLS)
    cert_obj = load_pem_x509_certificate((device_dir / "device.crt").read_bytes())
    cert_der = cert_obj.public_bytes(serialization.Encoding.DER)

    # Tenant scope baked into the signed cert — the device reports it (NFF_PROJECT_ID) so its
    # topics namespace as nff/{project_id}/devices/{device_id}/#.
    project_id = project_id_from_cert(cert_obj)
    if not project_id:
        raise ValueError(
            f"device cert for {device_id!r} has no project_id extension — re-provision with "
            "a project (issue_device_cert(device_id, project_id))"
        )

    # Device private key
    key_obj = serialization.load_pem_private_key(
        (device_dir / "device.key").read_bytes(), password=None
    )
    key_der = key_obj.private_bytes(
        serialization.Encoding.DER,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )

    # Project intermediate CA — the device presents leaf + intermediate in its TLS handshake so the
    # broker (cafile = root) can build the chain leaf → intermediate → root (§5 A1).
    intermediate_der = project_ca_cert_der(project_id)

    # CA cert — used by device to verify the broker's server certificate
    ca_obj = load_pem_x509_certificate(settings.tls_ca_cert.read_bytes())
    ca_der = ca_obj.public_bytes(serialization.Encoding.DER)

    # The device pins ITS PROJECT's command-verify key (per-project signing, §6): a command
    # signed for another project will not verify here.
    cmd_pub_bytes = signing.public_key_uncompressed(project_id)

    now = datetime.datetime.utcnow().isoformat()
    lines = [
        f"// credentials.h — generated by nff-fleet provision for device: {device_id}",
        f"// Project: {project_id}",
        "// Add to .gitignore. Contains the device private key — treat as a secret.",
        f"// Generated: {now}",
        "",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        f'// Tenant scope (bound in the signed device cert; topics namespace under it)',
        f'#define NFF_PROJECT_ID "{project_id}"',
        "",
        "// Per-device mTLS client certificate (CN = device_id, DER-encoded)",
        _to_c_array("NFF_CLIENT_CERT_DER", cert_der),
        "// Project intermediate CA — presented alongside the leaf so the broker builds the chain to root",
        _to_c_array("NFF_INTERMEDIATE_CERT_DER", intermediate_der),
        "// Per-device private key (P-256, PKCS#8 DER)",
        _to_c_array("NFF_CLIENT_KEY_DER", key_der),
        "// nff CA certificate — pinned; device rejects servers not signed by this CA",
        _to_c_array("NFF_CA_CERT_DER", ca_der),
        "// Project command-verify key (P-256 public, 65-byte uncompressed point)",
        _to_c_array("NFF_CMD_VERIFY_KEY_DER", cmd_pub_bytes),
        "// Firmware identity (injected by build system; override here for manual builds)",
        '#ifndef NFF_FW_VERSION',
        '#  define NFF_FW_VERSION  "1.0.0"',
        '#endif',
        '#ifndef NFF_BUILD_ID',
        '#  define NFF_BUILD_ID    "0000000000000000"',
        '#endif',
    ]
    return "\n".join(lines) + "\n"


def write_credentials_h(device_id: str, output_path: Path | None = None) -> Path:
    content = render_credentials_h(device_id)
    if output_path is None:
        output_path = settings.certs_dir / device_id / "credentials.h"
    output_path.write_text(content, encoding="utf-8")
    return output_path


def render_batch_bootstrap_h(project_id: str, batch_id: str) -> str:
    """Render the SHARED bootstrap credentials.h for a whole batch (DEVICE_OWNERSHIP_DESIGN.md §8).

    Identical for every device in the batch: shared batch cert/key + intermediate (so the broker can
    chain to root), the ROOT CA for verifying the broker's server cert, and the fleet rollover-verify
    key the device pins to authenticate the `rollover_cert` command that hands it its operational
    identity. No per-device material — uniqueness arrives later via rollover.
    """
    from nff_fleet.provisioning import batch as batch_mod

    batch_dir = batch_mod._batch_dir(batch_id)
    cert_obj = load_pem_x509_certificate((batch_dir / "bootstrap.crt").read_bytes())
    cert_der = cert_obj.public_bytes(serialization.Encoding.DER)

    key_obj = serialization.load_pem_private_key(
        (batch_dir / "bootstrap.key").read_bytes(), password=None
    )
    key_der = key_obj.private_bytes(
        serialization.Encoding.DER,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )

    intermediate_der = project_ca_cert_der(project_id)
    ca_obj = load_pem_x509_certificate(settings.tls_ca_cert.read_bytes())
    ca_der = ca_obj.public_bytes(serialization.Encoding.DER)
    rollover_pub = signing.rollover_verify_key_uncompressed()

    now = datetime.datetime.utcnow().isoformat()
    lines = [
        f"// credentials.h (BOOTSTRAP) — generated by nff-fleet for batch: {batch_id}",
        f"// Project: {project_id}",
        "// SHARED across the whole batch. Contains a private key — treat as a secret; valid 24h.",
        f"// Generated: {now}",
        "",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        "// Bootstrap mode marker — the SDK enters claim/announce mode when no NVS operational creds exist",
        "#define NFF_BOOTSTRAP 1",
        f'#define NFF_PROJECT_ID "{project_id}"',
        f'#define NFF_BATCH_ID "{batch_id}"',
        "",
        "// Shared batch bootstrap client certificate (CN = batch:{id}, DER-encoded)",
        _to_c_array("NFF_CLIENT_CERT_DER", cert_der),
        "// Project intermediate CA — presented alongside the leaf so the broker builds the chain to root",
        _to_c_array("NFF_INTERMEDIATE_CERT_DER", intermediate_der),
        "// Shared batch private key (P-256, PKCS#8 DER)",
        _to_c_array("NFF_CLIENT_KEY_DER", key_der),
        "// nff root CA — pinned; device rejects servers not signed by this CA",
        _to_c_array("NFF_CA_CERT_DER", ca_der),
        "// Fleet rollover-verify key (P-256 public, 65-byte uncompressed): authenticates rollover_cert",
        _to_c_array("NFF_ROLLOVER_VERIFY_KEY_DER", rollover_pub),
        "// Firmware identity (injected by build system; override here for manual builds)",
        '#ifndef NFF_FW_VERSION',
        '#  define NFF_FW_VERSION  "1.0.0"',
        '#endif',
        '#ifndef NFF_BUILD_ID',
        '#  define NFF_BUILD_ID    "0000000000000000"',
        '#endif',
    ]
    return "\n".join(lines) + "\n"


def write_batch_bootstrap_h(project_id: str, batch_id: str, output_path: Path | None = None) -> Path:
    content = render_batch_bootstrap_h(project_id, batch_id)
    if output_path is None:
        output_path = settings.certs_dir / "batches" / batch_id / "credentials.h"
    output_path.write_text(content, encoding="utf-8")
    return output_path
