import datetime
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509 import load_pem_x509_certificate

from nff_fleet.config import settings


def _to_c_array(name: str, data: bytes) -> str:
    hex_bytes = ", ".join(f"0x{b:02x}" for b in data)
    len_name = name.replace("_DER", "_LEN") if "_DER" in name else f"{name}_LEN"
    return (
        f"static const uint8_t {name}[] = {{\n    {hex_bytes}\n}};\n"
        f"#define {len_name} sizeof({name})\n"
    )


def render_credentials_h(device_id: str) -> str:
    device_dir = settings.certs_dir / device_id

    # Device client cert (mTLS)
    cert_obj = load_pem_x509_certificate((device_dir / "device.crt").read_bytes())
    cert_der = cert_obj.public_bytes(serialization.Encoding.DER)

    # Device private key
    key_obj = serialization.load_pem_private_key(
        (device_dir / "device.key").read_bytes(), password=None
    )
    key_der = key_obj.private_bytes(
        serialization.Encoding.DER,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )

    # CA cert — used by device to verify the broker's server certificate
    ca_obj = load_pem_x509_certificate(settings.tls_ca_cert.read_bytes())
    ca_der = ca_obj.public_bytes(serialization.Encoding.DER)

    # Command-signing public key — 65-byte uncompressed P-256 point
    cmd_key = serialization.load_pem_private_key(
        settings.cmd_sign_key.read_bytes(), password=None
    )
    cmd_pub: ec.EllipticCurvePublicKey = cmd_key.public_key()
    cmd_pub_bytes = cmd_pub.public_bytes(
        serialization.Encoding.X962,
        serialization.PublicFormat.UncompressedPoint,
    )

    now = datetime.datetime.utcnow().isoformat()
    lines = [
        f"// credentials.h — generated by nff-fleet provision for device: {device_id}",
        "// Add to .gitignore. Contains the device private key — treat as a secret.",
        f"// Generated: {now}",
        "",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        "// Per-device mTLS client certificate (CN = device_id, DER-encoded)",
        _to_c_array("NFF_CLIENT_CERT_DER", cert_der),
        "// Per-device private key (P-256, PKCS#8 DER)",
        _to_c_array("NFF_CLIENT_KEY_DER", key_der),
        "// nff CA certificate — pinned; device rejects servers not signed by this CA",
        _to_c_array("NFF_CA_CERT_DER", ca_der),
        "// Fleet command-verify key (P-256 public, 65-byte uncompressed point)",
        _to_c_array("NFF_CMD_VERIFY_KEY_DER", cmd_pub_bytes),
        "// Firmware identity (injected by build system; override here for manual builds)",
        '#ifndef NFF_FW_VERSION',
        '#  define NFF_FW_VERSION  "1.0.0"',
        '#endif',
        '#ifndef NFF_BUILD_ID',
        '#  define NFF_BUILD_ID    "0000000000000000"',
        '#endif',
    ]
    return "\n".join(lines) + "\n"


def write_credentials_h(device_id: str, output_path: Path | None = None) -> Path:
    content = render_credentials_h(device_id)
    if output_path is None:
        output_path = settings.certs_dir / device_id / "credentials.h"
    output_path.write_text(content, encoding="utf-8")
    return output_path
