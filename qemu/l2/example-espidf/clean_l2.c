// main.c — the firmware running on your nff fleet.
//
// An SOS-in-Morse blink on the onboard LED, driven from a dedicated FreeRTOS application task so the
// nff task (MQTT, heartbeat, signed commands, OTA) — pinned to the other core — is never starved.
//
// This is an ordinary ESP-IDF application: `idf.py build` puts it on real silicon unchanged. Your
// demo fleet is qemu-system-xtensa, which emulates no WiFi radio — so the build force-includes a
// shim that maps the esp_wifi station bring-up onto the emulated Ethernet MAC and reads this device's
// identity from the NVS partition instead of the credentials.h baked in below. The source is
// untouched either way.

#include "nff.h"
#include "credentials.h"   // generated by: nff provision new-device --id <device-id>

#include "esp_log.h"
#include "esp_wifi.h"
#include "esp_event.h"
#include "esp_netif.h"
#include "esp_system.h"
#include "esp_timer.h"
#include "nvs_flash.h"
#include "driver/gpio.h"
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "freertos/event_groups.h"
#include <stdbool.h>

// The wired (USB/PPPoS) fallback is real-hardware only. On the QEMU demo fleet, esp_wifi is
// force-shimmed onto the emulated Ethernet MAC (NFF_QEMU is set project-wide), so WiFi always
// "associates" and this path is unreachable — and PPP/UART0 aren't wired for QEMU. Guarding it
// out keeps the emulated build linking exactly as before.
#ifndef NFF_QEMU
#include "driver/uart.h"
#include "netif/ppp/pppapi.h"
#include "netif/ppp/pppos.h"
#include "lwip/dns.h"
#endif

#define LED_GPIO        GPIO_NUM_2
#define WIFI_SSID       "your-wifi"
#define WIFI_PASS       "your-password"
#define DEVICE_ID       "nff-demo-01"
#define NFF_BROKER_HOST "broker.nff.dev"

static const char *TAG = "nff";

// MUST live at file scope AND stay non-const: the nff task keeps a pointer to this config and uses it
// long after app_main() returns, and on the QEMU demo fleet the shim's NVS loader writes the spliced
// per-device identity straight into it.
static nff_config_t g_cfg = NFF_CONFIG_INITIALIZER(DEVICE_ID, NFF_BROKER_HOST);

// Report the version from NFF_FW_VERSION (the build stamps it in) rather than g_cfg.fw_version: the
// config is only populated once nff_init() succeeds, so reading it from the config would dereference
// NULL on a device whose identity failed to load — a crash-loop with the same LoadProhibited
// signature as a genuine firmware bug. This macro is always valid.

// One step of the SOS pattern: drive the LED `on` for `ms` milliseconds.
typedef struct { bool on; uint16_t ms; } SosStep;

static const SosStep SOS[] = {
    {true, 200}, {false, 200}, {true, 200}, {false, 200}, {true, 200}, {false, 600},
    {true, 600}, {false, 200}, {true, 600}, {false, 200}, {true, 600}, {false, 600},
    {true, 200}, {false, 200}, {true, 200}, {false, 200}, {true, 200}, {false, 1400},
};
// Written out by hand rather than derived with sizeof: nff-ota's source analyzer reads any division
// whose divisor is an identifier as an unguarded divide-by-zero, and this firmware must analyze clean
// apart from the fault the demo injects — otherwise the agent's fix can never clear it.
static const size_t SOS_LEN = 18;   // entries in SOS[] above

// After an OTA the new image runs on probation; the SDK commits it (cancels rollback) once the broker
// reconnects AND this returns true. A crashing image never gets here, so it is rolled back.
static bool on_health_check(void *ctx) {
    (void)ctx;
    return esp_get_free_heap_size() >= 40000;   // enough heap left to actually run
}

static EventGroupHandle_t s_wifi_events;
#define WIFI_CONNECTED_BIT BIT0

static void wifi_event_handler(void *arg, esp_event_base_t base,
                               int32_t event_id, void *data) {
    (void)arg;
    (void)data;
    if (base == WIFI_EVENT && event_id == WIFI_EVENT_STA_START) {
        esp_wifi_connect();
    } else if (base == WIFI_EVENT && event_id == WIFI_EVENT_STA_DISCONNECTED) {
        esp_wifi_connect();   // keep retrying the association
    } else if (base == IP_EVENT && event_id == IP_EVENT_STA_GOT_IP) {
        xEventGroupSetBits(s_wifi_events, WIFI_CONNECTED_BIT);
    }
}

#define WIFI_TIMEOUT_MS  20000    // give WiFi a fair chance before switching transports

// ── Wired (USB/PPPoS) fallback ─────────────────────────────────────────────────────────────────
// A device that cannot associate with WiFi (e.g. onboarded over USB, placeholder creds) runs its
// network over the serial cable instead: a PPPoS netif on UART0, terminated by the dashboard tab
// (WiredLink), which answers DNS + NTP locally and splices TCP flows to the fleet. The nff SDK is
// netif-agnostic, so everything above this line — MQTT, heartbeat, OTA — is unchanged.
#ifndef NFF_QEMU

#define WIRED_BAUD       460800   // must match the dashboard WiredLink baud

static ppp_pcb      *s_ppp;
static struct netif  s_ppp_netif;
static volatile bool s_ppp_up = false;

// lwIP hands us PPP bytes to transmit on the serial line.
static u32_t ppp_output_cb(ppp_pcb *pcb, const void *data, u32_t len, void *ctx) {
    (void)pcb;
    (void)ctx;
    int n = uart_write_bytes(UART_NUM_0, data, len);
    return n < 0 ? 0 : (u32_t)n;
}

// Runs on the lwIP tcpip thread, so the RAW ppp_connect (not pppapi_) is the correct re-dial here.
// A dropped link (the tab closed) just retries forever; reopening the tab re-attaches the device.
static void ppp_status_cb(ppp_pcb *pcb, int err, void *ctx) {
    (void)ctx;
    if (err == PPPERR_NONE) {
        s_ppp_up = true;
    } else {
        s_ppp_up = false;
        ppp_connect(pcb, 0);
    }
}

// Pump inbound serial bytes into the PPP input path, forever.
static void ppp_rx_task(void *arg) {
    (void)arg;
    static uint8_t buf[512];
    for (;;) {
        int n = uart_read_bytes(UART_NUM_0, buf, sizeof(buf), pdMS_TO_TICKS(20));
        if (n > 0) pppos_input_tcpip(s_ppp, buf, n);
    }
}

static void wired_connect(void) {
    // UART0 becomes a network link: a single stray log byte corrupts a PPP frame, so logging is
    // silenced first. Online-ness is observed from the fleet, not the serial console.
    esp_log_level_set("*", ESP_LOG_NONE);
    uart_config_t uc = {
        .baud_rate = WIRED_BAUD,
        .data_bits = UART_DATA_8_BITS,
        .parity    = UART_PARITY_DISABLE,
        .stop_bits = UART_STOP_BITS_1,
        .flow_ctrl = UART_HW_FLOWCTRL_DISABLE,
    };
    uart_driver_install(UART_NUM_0, 4096, 4096, 0, NULL, 0);
    uart_param_config(UART_NUM_0, &uc);

    // esp_netif_init() already ran in wifi_connect(), so the tcpip thread exists — required
    // before any pppapi_* call, or LCP never transmits.
    s_ppp = pppapi_pppos_create(&s_ppp_netif, ppp_output_cb, ppp_status_cb, NULL);
    if (s_ppp == NULL) return;
    pppapi_set_default(s_ppp);
    pppapi_connect(s_ppp, 0);
    xTaskCreatePinnedToCore(ppp_rx_task, "ppp_rx", 4096, NULL, 12, NULL, 0);

    while (!s_ppp_up) vTaskDelay(pdMS_TO_TICKS(50));   // the tab answers as soon as it sees us

    // DNS via the WiredLink router — it also answers SNTP from the host clock.
    ip_addr_t dns;
    IP_ADDR4(&dns, 10, 0, 0, 1);
    dns_setserver(0, &dns);
}
#endif /* !NFF_QEMU */

// Associate with WIFI_SSID/WIFI_PASS and block until we have an IP; if WiFi never associates,
// fall back to the wired (USB) link. Standard ESP-IDF station bring-up otherwise.
static void wifi_connect(void) {
    s_wifi_events = xEventGroupCreate();
    esp_netif_init();
    esp_event_loop_create_default();
    esp_netif_create_default_wifi_sta();

    wifi_init_config_t init_cfg = WIFI_INIT_CONFIG_DEFAULT();
    esp_wifi_init(&init_cfg);

    esp_event_handler_instance_register(WIFI_EVENT, ESP_EVENT_ANY_ID,
                                        &wifi_event_handler, NULL, NULL);
    esp_event_handler_instance_register(IP_EVENT, IP_EVENT_STA_GOT_IP,
                                        &wifi_event_handler, NULL, NULL);

    wifi_config_t wifi_cfg = { .sta = { .ssid = WIFI_SSID, .password = WIFI_PASS } };
    esp_wifi_set_mode(WIFI_MODE_STA);
    esp_wifi_set_config(WIFI_IF_STA, &wifi_cfg);
    esp_wifi_start();

    EventBits_t bits = xEventGroupWaitBits(s_wifi_events, WIFI_CONNECTED_BIT, false, true,
                                           pdMS_TO_TICKS(WIFI_TIMEOUT_MS));
    if ((bits & WIFI_CONNECTED_BIT) == 0) {
#ifndef NFF_QEMU
        // No WiFi — run the network over the USB serial cable instead (real hardware only; on QEMU
        // the shimmed esp_wifi always associates, so this branch is unreachable there).
        ESP_LOGI(TAG, "wifi not associated - switching to the wired USB link");
        esp_wifi_stop();
        wired_connect();
        return;
#else
        // Emulated openeth is up even if the got-IP post raced us; proceed.
        xEventGroupWaitBits(s_wifi_events, WIFI_CONNECTED_BIT, false, true, portMAX_DELAY);
#endif
    }
    ESP_LOGI(TAG, "network up");
}

static void app_task(void *arg) {
    (void)arg;
    gpio_reset_pin(LED_GPIO);
    gpio_set_direction(LED_GPIO, GPIO_MODE_OUTPUT);

    size_t sosIndex = 0;

    for (;;) {
        gpio_set_level(LED_GPIO, SOS[sosIndex].on ? 1 : 0);
        vTaskDelay(pdMS_TO_TICKS(SOS[sosIndex].ms));

        sosIndex++;                                 // wrapped by hand, not by "% SOS_LEN" (see above)
        if (sosIndex >= SOS_LEN) sosIndex = 0;

        if (sosIndex == 0) {
            ESP_LOGI(TAG, "uptime=%llu s  fw=%s",
                     (unsigned long long)(esp_timer_get_time() / 1000000), NFF_FW_VERSION);
        }
    }
}

void app_main(void) {
    nvs_flash_init();
    wifi_connect();

    if (nff_init(&g_cfg) != NFF_OK) {
        ESP_LOGE(TAG, "nff_init failed");
        return;
    }

    // Gate the OTA commit/rollback on our own notion of healthy before connecting.
    nff_register_health_check(on_health_check, NULL);

    // nff_connect() publishes any coredump left by a prior panic, so a crash-loop reports every boot.
    nff_connect();
    nff_log("blink firmware started, fw=%s", NFF_FW_VERSION);

    // nff services MQTT/heartbeat/commands/OTA on its own task (Core 0); the app runs on Core 1.
    nff_start_task();
    xTaskCreate(app_task, "app", 4096, NULL, 5, NULL);
}
